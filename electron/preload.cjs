const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
  isElectron: true,
  getVersion: () => ipcRenderer.invoke('get-app-version'),
  printPage: () => ipcRenderer.invoke('print-page'),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  openPath: (p) => ipcRenderer.invoke('open-path', p),
  showItemInFolder: (p) => ipcRenderer.invoke('show-item-in-folder', p),
  copyFileToClipboard: (p) => ipcRenderer.invoke('copy-file-to-clipboard', p),
  sendWhatsAppFile: (data) => ipcRenderer.invoke('send-whatsapp-file', data),
  shareFile: (data) => ipcRenderer.invoke('share-file', data),
  exportPdfInvoice: (data) => ipcRenderer.invoke('export-pdf-invoice', data),
  printHtmlDirect: (data) => ipcRenderer.invoke('print-html-direct', data),
  getPrinters: () => ipcRenderer.invoke('get-printers'),
  saveFileDialog: (data) => ipcRenderer.invoke('save-file-dialog', data),
  db: {
    checkConnection: () => ipcRenderer.invoke('db:check-connection'),
    getTransactions: (limit) => ipcRenderer.invoke('db:get-transactions', limit),
    saveTransaction: (tx) => ipcRenderer.invoke('db:save-transaction', tx),
    deleteTransaction: (id) => ipcRenderer.invoke('db:delete-transaction', id),
    getContacts: () => ipcRenderer.invoke('db:get-contacts'),
    saveContact: (contact) => ipcRenderer.invoke('db:save-contact', contact),
    deleteContact: (id) => ipcRenderer.invoke('db:delete-contact', id),
    getFishTypes: () => ipcRenderer.invoke('db:get-fish-types'),
    saveFishType: (fish) => ipcRenderer.invoke('db:save-fish-type', fish),
    deleteFishType: (id) => ipcRenderer.invoke('db:delete-fish-type', id),
    getCashEntries: (limit) => ipcRenderer.invoke('db:get-cash-entries', limit),
    saveCashEntry: (entry) => ipcRenderer.invoke('db:save-cash-entry', entry),
    deleteCashEntry: (id) => ipcRenderer.invoke('db:delete-cash-entry', id),
    getCashClosings: (limit) => ipcRenderer.invoke('db:get-cash-closings', limit),
    saveCashClosing: (closing) => ipcRenderer.invoke('db:save-cash-closing', closing),
    getSettings: () => ipcRenderer.invoke('db:get-settings'),
    saveSettings: (settings) => ipcRenderer.invoke('db:save-settings', settings),
  },
});
